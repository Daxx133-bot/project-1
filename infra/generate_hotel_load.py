#!/usr/bin/env python3
"""
generate_hotel_load.py — Baseline Load Generator for Hotel Reservation
=======================================================================
Generates sustained baseline load against the Hotel Reservation application
using Locust. The load covers all 8 application services by exercising:
  - Hotel search (frontend → search → geo + rate + profile)  60% of requests
  - Hotel reservation (frontend → reservation → user)         20% of requests
  - User lookup (frontend → user)                             20% of requests

This is needed before fault injection experiments to:
  1. Warm up the JVM / Go runtime (DSB Hotel is written in Go)
  2. Generate a steady stream of Jaeger traces for the SDG
  3. Establish a performance baseline for blast radius measurement

Usage:
    python infra/generate_hotel_load.py
    python infra/generate_hotel_load.py --duration 120 --rate 50
    python infra/generate_hotel_load.py --mode direct  # no Locust, use raw requests
"""

import argparse
import random
import subprocess
import sys
import tempfile
import time
from pathlib import Path

DEFAULT_BASE_URL = "http://localhost:5000"
DEFAULT_DURATION = 60
DEFAULT_RATE = 50

LOCUSTFILE_CONTENT = '''
"""
_locustfile_hotel.py — Locust load task definitions for Hotel Reservation.
Auto-generated by generate_hotel_load.py. Do not edit manually.
"""

import random
from locust import HttpUser, task, between

HOTEL_LOCATIONS = [
    (37.7867, -122.4112),
    (37.7794, -122.4062),
    (38.0235, -122.095),
    (37.6879, -122.4702),
    (37.3382, -121.8863),
]

DATE_PAIRS = [
    ("2015-04-09", "2015-04-10"),
    ("2015-04-10", "2015-04-11"),
    ("2015-04-11", "2015-04-12"),
]

USERS = [f"Cornell_{i}" for i in range(1, 51)]
HOTELS = list(range(1, 21))


class HotelUser(HttpUser):
    wait_time = between(0.5, 1.5)

    @task(6)
    def hotel_search(self):
        lat, lon = random.choice(HOTEL_LOCATIONS)
        in_date, out_date = random.choice(DATE_PAIRS)
        with self.client.get(
            "/hotels",
            params={"inDate": in_date, "outDate": out_date,
                    "lat": str(lat), "lon": str(lon)},
            catch_response=True,
            name="/hotels [search]",
        ) as r:
            if r.status_code >= 500:
                r.failure(f"Server error: {r.status_code}")

    @task(2)
    def make_reservation(self):
        in_date, out_date = random.choice(DATE_PAIRS)
        with self.client.post(
            "/reservation",
            json={
                "customerName": random.choice(USERS),
                "hotelId": str(random.choice(HOTELS)),
                "inDate": in_date,
                "outDate": out_date,
                "roomNumber": random.randint(1, 100),
            },
            catch_response=True,
            name="/reservation [book]",
        ) as r:
            if r.status_code >= 500:
                r.failure(f"Server error: {r.status_code}")

    @task(2)
    def get_user(self):
        with self.client.get(
            "/user",
            params={"username": random.choice(USERS)},
            catch_response=True,
            name="/user [lookup]",
        ) as r:
            if r.status_code >= 500:
                r.failure(f"Server error: {r.status_code}")

    @task(1)
    def get_recommendations(self):
        lat, lon = random.choice(HOTEL_LOCATIONS)
        with self.client.get(
            "/recommendations",
            params={"require": random.choice(["dis", "rate", "price"]),
                    "lat": str(lat), "lon": str(lon)},
            catch_response=True,
            name="/recommendations",
        ) as r:
            if r.status_code >= 500:
                r.failure(f"Server error: {r.status_code}")
'''


def run_with_locust(base_url: str, duration: int, rate: int) -> bool:
    """Run load with Locust headless."""
    print(f"[INFO] Starting Locust load: {rate} users, {duration}s, target={base_url}")

    # Write locustfile to temp location
    locust_path = Path(__file__).parent / "_locustfile_hotel.py"
    locust_path.write_text(LOCUSTFILE_CONTENT, encoding="utf-8")

    cmd = [
        sys.executable, "-m", "locust",
        "-f", str(locust_path),
        "--host", base_url,
        "--headless",
        "--users", str(rate),
        "--spawn-rate", "10",
        "--run-time", f"{duration}s",
        "--csv", "hotel_load_stats",
        "--loglevel", "WARNING",
    ]

    print(f"  Command: {' '.join(cmd)}")
    try:
        result = subprocess.run(cmd, timeout=duration + 60)
        success = result.returncode == 0
        if success:
            print(f"[OK] Locust completed ({rate} users × {duration}s).")
        else:
            print(f"[WARNING] Locust exited with code {result.returncode}")
        return success
    except subprocess.TimeoutExpired:
        print("[WARNING] Locust timed out")
        return False
    except FileNotFoundError:
        print("[ERROR] Locust not found. Install: pip install locust")
        return False


def run_direct(base_url: str, duration: int, rate: int) -> None:
    """Fallback: direct HTTP requests without Locust."""
    import requests
    import threading

    print(f"[INFO] Direct load: {rate} threads, {duration}s, target={base_url}")

    HOTEL_LOCATIONS = [(37.7867, -122.4112), (38.0235, -122.095)]
    DATE_PAIRS = [("2015-04-09", "2015-04-10"), ("2015-04-10", "2015-04-11")]
    USERS = [f"Cornell_{i}" for i in range(1, 11)]

    stop_event = threading.Event()
    request_counts = {"ok": 0, "fail": 0}
    lock = threading.Lock()

    def worker():
        s = requests.Session()
        while not stop_event.is_set():
            try:
                lat, lon = random.choice(HOTEL_LOCATIONS)
                in_d, out_d = random.choice(DATE_PAIRS)
                roll = random.random()
                if roll < 0.6:
                    r = s.get(f"{base_url}/hotels",
                              params={"inDate": in_d, "outDate": out_d,
                                      "lat": str(lat), "lon": str(lon)}, timeout=5)
                elif roll < 0.8:
                    r = s.post(f"{base_url}/reservation",
                               json={"customerName": random.choice(USERS),
                                     "hotelId": str(random.randint(1, 20)),
                                     "inDate": in_d, "outDate": out_d,
                                     "roomNumber": random.randint(1, 100)}, timeout=5)
                else:
                    r = s.get(f"{base_url}/user",
                              params={"username": random.choice(USERS)}, timeout=5)

                with lock:
                    if r.status_code < 500:
                        request_counts["ok"] += 1
                    else:
                        request_counts["fail"] += 1
            except Exception:
                with lock:
                    request_counts["fail"] += 1
            time.sleep(random.uniform(0.1, 0.5))

    threads = [threading.Thread(target=worker, daemon=True) for _ in range(min(rate, 20))]
    for t in threads:
        t.start()

    start = time.time()
    while time.time() - start < duration:
        elapsed = int(time.time() - start)
        with lock:
            ok, fail = request_counts["ok"], request_counts["fail"]
        print(f"  [{elapsed:3d}s] OK={ok}, FAIL={fail}")
        time.sleep(10)

    stop_event.set()
    for t in threads:
        t.join(timeout=5)

    print(f"\n[OK] Direct load complete: {request_counts['ok']} OK, {request_counts['fail']} FAIL")


def main():
    parser = argparse.ArgumentParser(
        description="Generate baseline load for Hotel Reservation benchmark"
    )
    parser.add_argument("--base-url", default=DEFAULT_BASE_URL,
                        help=f"Hotel frontend URL (default: {DEFAULT_BASE_URL})")
    parser.add_argument("--duration", type=int, default=DEFAULT_DURATION,
                        help=f"Load duration in seconds (default: {DEFAULT_DURATION})")
    parser.add_argument("--rate", type=int, default=DEFAULT_RATE,
                        help=f"Concurrent users (default: {DEFAULT_RATE})")
    parser.add_argument("--mode", choices=["locust", "direct", "auto"], default="auto",
                        help="Load generator mode (default: auto — tries locust, falls back to direct)")
    args = parser.parse_args()

    print("=" * 60)
    print("  Hotel Reservation — Baseline Load Generation")
    print("=" * 60)
    print(f"  Target:   {args.base_url}")
    print(f"  Duration: {args.duration}s")
    print(f"  Rate:     {args.rate} users")
    print(f"  Mode:     {args.mode}")
    print("=" * 60)

    if args.mode == "locust":
        run_with_locust(args.base_url, args.duration, args.rate)
    elif args.mode == "direct":
        run_direct(args.base_url, args.duration, args.rate)
    else:
        # Auto: try Locust first, fall back to direct
        try:
            import locust
            run_with_locust(args.base_url, args.duration, args.rate)
        except ImportError:
            print("[INFO] Locust not available, falling back to direct HTTP mode.")
            run_direct(args.base_url, args.duration, args.rate)

    print(f"\n[INFO] Load generation complete.")
    print(f"[INFO] Check traces at: http://localhost:16687")
    print(f"[INFO] Next step: python sdg/trace_collector.py --jaeger-url http://localhost:16687")


if __name__ == "__main__":
    main()
